// Composes Bleek's Prisma schema from two sources:
//   1. node_modules/@astro/core/prisma/astro.prisma — the account models ASTRO owns
//   2. prisma/schema/bleek.prisma — Bleek's own models
// The package ships a standalone generator/datasource block for its own project;
// it is stripped here so Bleek's single datasource stays authoritative. The one
// thing the package cannot know is Bleek's back-relations on User, so they are
// injected from prisma/schema/user-relations.inc.
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const source = join(root, "node_modules/@astro/core/prisma/astro.prisma");
const relationsFile = join(root, "prisma/schema/user-relations.inc");
const target = join(root, "prisma/schema/astro.prisma");

if (!existsSync(source)) {
  console.error(`[astro] @astro/core is not installed at ${source}. Run npm install first.`);
  process.exit(1);
}
if (!existsSync(relationsFile)) {
  console.error(`[astro] missing ${relationsFile}; it declares Bleek's back-relations on User.`);
  process.exit(1);
}

const relations = readFileSync(relationsFile, "utf8").trimEnd();
let schema = readFileSync(source, "utf8").replace(/\n\/\/ <astro:standalone>[\s\S]*?\/\/ <\/astro:standalone>/, "");

if (!schema.includes("// @astro:user-relations")) {
  console.error("[astro] the package schema is missing the @astro:user-relations marker; refusing to write a partial schema.");
  process.exit(1);
}

schema = `${schema.replace("// @astro:user-relations", relations)}\n// Generated by scripts/sync-astro-schema.mjs from @astro/core. Do not edit.\n`;

mkdirSync(dirname(target), { recursive: true });
writeFileSync(target, schema);
console.log(`[astro] synced account models from @astro/core with ${relations.split("\n").length} Bleek relations.`);
